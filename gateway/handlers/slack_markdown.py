_SHORTCODE = re.compile(r":([a-z0-9_+\-]+)(?:::skin-tone-\d)?:")
_LINK = re.compile(r"<((?:https?|mailto):[^|>\s]+)(?:\|([^>]*))?>")
_SPECIAL = re.compile(r"<(?:!(?:here|channel|everyone)(?:\|[^>]*)?|@[A-Z0-9]+(?:\|[^>]*)?)>")
_CHANNEL = re.compile(r"<#[A-Z0-9]+\|([^>]*)>")
# Slack 粗體 *字*、刪除線 ~字~（不碰 Markdown 已經是 ** 的）
_BOLD = re.compile(r"(?<![*A-Za-z0-9])\*(?!\s)([^*\n]+?)(?<!\s)\*(?![*A-Za-z0-9])")
_STRIKE = re.compile(r"(?<![~A-Za-z0-9])~(?!\s)([^~\n]+?)(?<!\s)~(?![~A-Za-z0-9])")


def emojize(text: str) -> str:
    """``:ship:`` → 🚢；不認得的代碼拿掉。"""
    return _SHORTCODE.sub(lambda m: EMOJI.get(m.group(1), ""), text or "")


def _link(m: re.Match) -> str:
    url, label = m.group(1), (m.group(2) or "").strip()
    if url.startswith("mailto:"):
        return label or url[len("mailto:") :]
    bare = re.sub(r"^https?://", "", url)
    # Slack 自動產生的顯示文字（網址本身、或被縮成「domain/…/path」）→ 直接放網址
    if not label or label == url or "…" in label or bare.startswith(label.rstrip("/")):
        return f"[{url}]({url})"
    return f"[{label}]({url})"


def to_markdown(text: str) -> str:
    """Slack mrkdwn → 網站 Markdown（表情、連結、粗體、刪除線、提及）。"""
    s = text or ""
    s = _LINK.sub(_link, s)
    s = _CHANNEL.sub(lambda m: f"#{m.group(1)}", s)
    s = _SPECIAL.sub("", s)
    s = emojize(s)
    s = _BOLD.sub(r"**\1**", s)
    s = _STRIKE.sub(r"~~\1~~", s)
    return html.unescape(s)
